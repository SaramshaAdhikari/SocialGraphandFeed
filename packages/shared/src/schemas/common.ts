import { Type, type Static, type TSchema, FormatRegistry } from '@sinclair/typebox';

// Register standard JSON Schema formats for TypeBox Value validation
if (!FormatRegistry.Has('date-time')) {
  FormatRegistry.Set('date-time', (value: string) => !isNaN(Date.parse(value)));
}

// Register URI format supporting absolute URLs and root-relative paths
FormatRegistry.Set('uri', (value: string) => {
  if (typeof value !== 'string') return false;
  if (value.startsWith('/') || value.startsWith('./')) return true;
  try {
    const u = new URL(value);
    return Boolean(u.protocol);
  } catch {
    return false;
  }
});

/**
 * Standard RFC 7807 problem details error response schema.
 */
export const ApiErrorResponseSchema = Type.Object({
  type: Type.String({ description: 'URI reference identifying the problem type' }),
  title: Type.String({ description: 'Short, human-readable summary of the problem type' }),
  status: Type.Integer({ description: 'HTTP status code generated by origin server' }),
  detail: Type.String({ description: 'Human-readable explanation specific to this occurrence' }),
  instance: Type.Optional(Type.String({ description: 'URI reference identifying this specific problem occurrence' })),
  code: Type.String({ description: 'Machine-readable application error code (e.g. NOT_FOUND, VALIDATION_ERROR)' }),
  request_id: Type.Optional(Type.String({ description: 'Unique request identifier for tracing' })),
  retry_after: Type.Optional(Type.Integer({ description: 'Recommended seconds to wait before retrying' })),
  invalidParams: Type.Optional(
    Type.Array(
      Type.Object({
        name: Type.String(),
        reason: Type.String(),
      })
    )
  ),
  timestamp: Type.String(),
});

export type ApiErrorResponse = Static<typeof ApiErrorResponseSchema>;

/**
 * Factory for building cursor-paginated response schemas.
 */
export function createPaginatedResponseSchema<T extends TSchema>(itemSchema: T) {
  return Type.Object({
    success: Type.Literal(true),
    data: Type.Array(itemSchema),
    next_cursor: Type.Union([Type.String(), Type.Null()]),
    has_more: Type.Boolean(),
    meta: Type.Object({
      count: Type.Integer({ minimum: 0 }),
      server_execution_time_ms: Type.Number({ minimum: 0 }),
    }),
  });
}

/**
 * Common pagination query parameters.
 */
export const PaginationQuerySchema = Type.Object({
  cursor: Type.Optional(Type.String({ maxLength: 2048, description: 'Opaque pagination cursor' })),
  limit: Type.Optional(Type.Integer({ minimum: 1, maximum: 100, default: 20 })),
});

export type PaginationQuery = Static<typeof PaginationQuerySchema>;
